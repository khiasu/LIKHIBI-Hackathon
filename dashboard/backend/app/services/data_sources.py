def _imported(path: Path) -> bool:
    if path.is_file():
        return path.stat().st_size > 0
    if path.is_dir():
        return any(child.name != ".gitkeep" for child in path.iterdir())
    return False


def list_sources(datasets_dir: Path) -> list[dict[str, Any]]:
    return [
        {**asdict(source), "imported": _imported(datasets_dir / source.expected_path)}
        for source in SOURCES
    ]
