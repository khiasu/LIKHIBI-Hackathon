    /** Emoji whose Unicode name or keywords contain every word of the query. */
    fun search(query: String, pool: List<String>): List<String> {
        val words = query.lowercase().split(' ').filter { it.isNotBlank() }
        if (words.isEmpty()) return emptyList()
        val fromKeywords = KEYWORDS.filterKeys { key -> words.any { key.startsWith(it) } }.values.flatten()
        val fromNames = pool.filter { emoji ->
            val name = runCatching { Character.getName(emoji.codePointAt(0)) }.getOrNull()?.lowercase().orEmpty()
            words.all { name.contains(it) }
        }
        return (fromKeywords + fromNames).distinct()
    }
