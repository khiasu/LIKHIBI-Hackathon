"""
Build the Likhibi Nagamese lexicon from attested and curated sources, with provenance.

Lists only words that real Nagamese text or a curated list contains, never forms
generated by gluing suffixes onto stems, and records for every word where it came
from and how each annotation was made.

Sources, in order of trust:
    isv-nagamese-nt         ISV Nagamese New Testament, CC BY-SA 4.0 (counts from real text)
    likhibi-keyboard        the keyboard's hand-curated everyday word list (NagameseOfflineEngine.kt)
    vocab:<file>#<section>  earlier thematic word lists in datasets/raw/vocabulary/, collected from
                            references listed in each file's header; their sections give domains
                            (food, family, slang ...). Sections marked as web-scraped or Hindi
                            are only candidates until a speaker accepts them.

Annotations, each with its method recorded:
    part of speech   Universal POS tags: hand-tagged function words (closed_class.py); verb
                     paradigms found by suffix analysis; English tags projected through IBM
                     Model 1 word alignments of the parallel verses (Yarowsky and Ngai, 2001);
                     the domain of curated lists (a word from "VERBS" is a verb)
    morphology       root and suffix for verb forms (kor- + -ise, past), plurals in -khan,
                     postpositions written attached (moi + laga)
    variants         spellings that differ only in ways Nagamese writers vary (sh/s, ee/i,
                     oo/u, v/b, doubled letters), grouped under the most frequent form
    glosses          candidate English meanings from the aligned verses, never shown as verified
    register         scripture, everyday or both, from which sources attest the word
    display form     capitalised names (Jisu, Khrista) learned from mid-sentence capitals

Nothing here is marked verified: a speaker verifies entries with the review file.

    python -m nlp_research.lexicon.build_lexicon
"""

