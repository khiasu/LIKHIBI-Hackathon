# Verb suffixes (Nagamese tense, aspect and mood endings). "Strong" ones rarely end
# other words, so a single one is evidence; short ones only count inside a paradigm.
STRONG_SUFFIXES = {"isile": "past perfect", "ibole": "infinitive, purpose", "bole": "infinitive, purpose",
                   "ikena": "having done", "ikene": "having done", "ise": "past", "ibo": "future",
                   "ile": "conditional, when", "se": "past"}
WEAK_SUFFIXES = {"ibi": "imperative, future (you)", "bo": "future", "bi": "imperative, future (you)",
                 "e": "present, habitual", "i": "non-finite, ongoing"}
ATTACHED_POSTPOSITIONS = ("logote", "logot", "nimite", "laga", "pora", "te", "ke")
# Function-word tags come only from the hand-tagged list: an alignment to English "the"
# or "to" says little about a Nagamese content word.
CLOSED_TAGS = {"DET", "ADP", "PRON", "CCONJ", "SCONJ", "PART", "AUX"}


@dataclass
class Entry:
    word: str
    nt_count: int = 0
    keyboard_weight: int = 0
    display: str = ""
    sources: list = field(default_factory=list)
    domains: set = field(default_factory=set)
    origin: str = ""
    noisy_only: bool = True
    section_pos: str = ""
    pos: str = "Unknown"
    pos_method: str = ""
    pos_confidence: float = 0.0
    root: str = ""
    morphology: str = ""
    features: list = field(default_factory=list)
    glosses: list = field(default_factory=list)
    canonical: str = ""
    variants: list = field(default_factory=list)


def fold(word: str) -> str:
    """The spelling-variant key: sh/s, ee/i, oo/u, v/b and doubled letters treated as one."""
    word = word.replace("sh", "s").replace("ee", "i").replace("oo", "u").replace("v", "b")
    return re.sub(r"(.)\1+", r"\1", word)


def read_vocab_sections(path: Path) -> list[tuple[str, str]]:
    """(word, section heading) for every word line in an earlier thematic list."""
    section, found = "", []
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if stripped.startswith("#"):
            heading = stripped.strip("#= ").strip()
            if heading and not set(heading) <= set("="):
                section = heading
            continue
        word = stripped.lower()
        if word:
            found.append((word, section))
    return found


def domain_for(section: str) -> str | None:
    lowered = section.lower()
    return next((domain for key, domain in DOMAIN_KEYWORDS if key in lowered), None)


def section_kind(section: str) -> str:
    lowered = section.lower()
    if "scrap" in lowered or "automated" in lowered:
        return "scraped"
    if "hindi" in lowered:
        return "hindi"
    if "variant" in lowered:
        return "variants"
    if "english" in lowered or "loanword" in lowered or "borrowed" in lowered or "code-switching" in lowered:
        return "english"
    return "nagamese"


def nt_counts_and_display() -> tuple[Counter, dict[str, str]]:
    """Word counts from the New Testament, and the capitalised form of words written as names."""
    tokenizer = NagameseTokenizer()
    counts: Counter = Counter()
    capitalised: Counter = Counter()
    seen_mid: Counter = Counter()
    for sentence in sentences():
        counts.update(tokenizer.tokenize(sentence))
        # A word right after the start, a full stop, colon or opening quote is capitalised
        # by position; only capitals elsewhere say a word is a name.
        for match in re.finditer(r"(?:(^)|([.?!:;“\"‘'(]\s*)|\s)([A-Za-z]{2,})", sentence):
            token = match.group(3)
            if match.group(1) is not None or match.group(2):
                continue
            seen_mid[token.lower()] += 1
            if token[0].isupper():
                capitalised[token] += 1
    # Common words keep lowercase even when the Bible capitalises them (Isor, Probhu):
    # a display form is only for names, never for a word on the keyboard's everyday list.
    everyday = set(builtin_words())
    display = {}
    for token, count in capitalised.items():
        word = token.lower()
        if count >= 3 and count / seen_mid[word] >= 0.9 and word not in CLOSED_CLASS and word not in everyday:
            display[word] = token
    return counts, display


def project_pos(pairs: list[tuple[str, str]], iterations: int = 5) -> dict[str, Counter]:
    """Tag the English side, align words with IBM Model 1 both ways, and let each Nagamese word vote."""
    import nltk

    from nlp_research.translation.glossary import _ibm_model1

    tokenizer = NagameseTokenizer()
    tokenised = []
    for english, nagamese in pairs:
        en_tokens = re.findall(r"[A-Za-z]+(?:'[a-z]+)?", english)
        nag_tokens = tokenizer.tokenize(nagamese)
        if en_tokens and nag_tokens and len(en_tokens) <= 80 and len(nag_tokens) <= 80:
            tokenised.append((en_tokens, nag_tokens))
    lowered = [([w.lower() for w in en], nag) for en, nag in tokenised]
    nag_given_en = _ibm_model1(lowered, iterations)  # t[nag][en]
    en_given_nag = _ibm_model1([(nag, en) for en, nag in lowered], iterations)  # t[en][nag]
    votes: dict[str, Counter] = defaultdict(Counter)
    for (en_tokens, nag_tokens), (en_lower, _) in zip(tokenised, lowered):
        tags = [tag for _, tag in nltk.pos_tag(en_tokens)]
        for nag in set(nag_tokens):
            row = nag_given_en.get(nag, {})
            best, best_score = -1, 0.0
            for index, english in enumerate(en_lower):
                score = row.get(english, 0.0) * en_given_nag.get(english, {}).get(nag, 0.0)
                if score > best_score:
                    best, best_score = index, score
            if best >= 0 and best_score > 1e-4:
                upos = PTB_TO_UPOS.get(tags[best])
                if upos is None and tags[best].startswith("VB"):
                    upos = "VERB"
                if upos:
                    votes[nag][upos] += 1
    return votes


def analyse_verbs(words: set[str]) -> dict[str, tuple[str, str, str]]:
    """word -> (root, suffix, meaning) for forms of verbs whose root takes at least three endings."""
    endings = sorted({**STRONG_SUFFIXES, **WEAK_SUFFIXES}.items(), key=lambda item: -len(item[0]))
    split: dict[str, tuple[str, str]] = {}
    for word in words:
        bare = word[2:] if word.startswith("na") and word[2:] in words else word
        for suffix, _ in endings:
            if bare.endswith(suffix) and len(bare) - len(suffix) >= 2:
                split[word] = (bare[: -len(suffix)], suffix)
                break
    paradigm: dict[str, set[str]] = defaultdict(set)
    for root, suffix in split.values():
        paradigm[root].add(suffix)
    analyses = {}
    for word, (root, suffix) in split.items():
        if len(paradigm[root]) >= 3:
            meaning = {**STRONG_SUFFIXES, **WEAK_SUFFIXES}[suffix]
            if word.startswith("na") and not word.startswith(root):
                meaning = "negative, " + meaning
            analyses[word] = (root, suffix, meaning)
    return analyses


def load_glosses() -> dict[str, list[dict]]:
    found: dict[str, list[dict]] = defaultdict(list)
    if GLOSSARY_TSV.is_file():
        with GLOSSARY_TSV.open(encoding="utf-8", newline="") as handle:
            for row in csv.DictReader(handle, delimiter="\t"):
                found[row["nagamese"]].append({"english": row["english"], "score": float(row["score"]), "method": "ibm1-aligned-verses"})
    return found


DECISION_COLUMNS = ("word", "decision", "correct_pos", "correct_gloss", "note", "reviewer", "date")


def collect_decisions(reviewer: str) -> dict[str, dict]:
    """Speaker decisions: those saved earlier, plus any newly filled in the review queue.

    A filled queue row is moved into lexicon_decisions.tsv before the queue is rewritten,
    so a rebuild never loses a decision.
    """
    decisions: dict[str, dict] = {}
    if DECISIONS_TSV.is_file():
        with DECISIONS_TSV.open(encoding="utf-8", newline="") as handle:
            for row in csv.DictReader(handle, delimiter="\t", quoting=csv.QUOTE_NONE):
                decisions[row["word"]] = row
    if REVIEW_TSV.is_file():
        with REVIEW_TSV.open(encoding="utf-8", newline="") as handle:
            for row in csv.DictReader(handle, delimiter="\t", quoting=csv.QUOTE_NONE):
                if (row.get("decision") or "").strip():
                    decisions[row["word"]] = {
                        "word": row["word"], "decision": row["decision"].strip().lower(),
                        "correct_pos": (row.get("correct_pos") or "").strip().upper(),
                        "correct_gloss": (row.get("correct_gloss") or "").strip(),
                        "note": (row.get("note") or "").strip(), "reviewer": reviewer, "date": time.strftime("%Y-%m-%d"),
                    }
    with DECISIONS_TSV.open("w", encoding="utf-8", newline="") as handle:
        handle.write("\t".join(DECISION_COLUMNS) + "\n")
        for row in decisions.values():
            handle.write("\t".join((row.get(c) or "").replace("\t", " ") for c in DECISION_COLUMNS) + "\n")
    return decisions


def build(reviewer: str = "speaker") -> dict:
    tokenizer_word = re.compile(r"^[a-z]{2,}$")
    decisions = collect_decisions(reviewer)
    entries: dict[str, Entry] = {}

    def entry(word: str) -> Entry:
        return entries.setdefault(word, Entry(word))

    counts, display = nt_counts_and_display()
    for word, count in counts.items():
        e = entry(word)
        e.nt_count = count
        e.noisy_only = False
        e.sources.append({"name": NT_SOURCE, "license": "CC BY-SA 4.0", "count": count})
        if word in display:
            e.display = display[word]

    for word, weight in builtin_words().items():
        if not tokenizer_word.match(word):
            continue
        e = entry(word)
        e.keyboard_weight = weight
        e.noisy_only = False
        e.sources.append({"name": KEYBOARD_SOURCE, "weight": weight})

    for word, (proper, domain) in NAGA_PROPER_NOUNS.items():
        e = entry(word)
        e.display = proper
        e.domains.add(domain)
        e.noisy_only = False
        e.sources.append({"name": "naga-place-and-tribe-names"})

    rejected: list[tuple[str, str, str]] = []
    for filename in VOCAB_FILES:
        for word, section in read_vocab_sections(VOCAB_DIR / filename):
            if not tokenizer_word.match(word):
                rejected.append((word, f"vocab:{filename}#{section}", "not a single lowercase word"))
                continue
            kind = section_kind(section)
            e = entry(word)
            e.sources.append({"name": f"vocab:{filename}#{section}", "kind": kind})
            if kind in ("nagamese", "english"):
                e.noisy_only = False
            if kind == "english" and not e.origin:
                e.origin = "English loanword"
            elif kind == "hindi" and not e.origin:
                e.origin = "Hindi loanword (to check)"
            domain = domain_for(section)
            if domain and kind != "scraped":
                e.domains.add(domain)
            pos_hint = next((pos for key, pos in SECTION_POS if key in section.lower()), "")
            if pos_hint and kind == "nagamese" and not e.section_pos:
                e.section_pos = pos_hint

    # Part of speech: hand-tagged function words, then verb paradigms, then projection, then list domains.
    from nlp_research.translation.bank import DEFAULT_DATASETS_DIR, load_examples

    pairs = [(ex.english, ex.nagamese) for ex in load_examples(DEFAULT_DATASETS_DIR)]
    votes = project_pos(pairs)
    attested = {w for w, e in entries.items() if e.nt_count}
    verbs = analyse_verbs(attested)
    glosses = load_glosses()

    for word, e in entries.items():
        if word in CLOSED_CLASS:
            e.pos, e.pos_method, e.pos_confidence = CLOSED_CLASS[word][0], "hand-tagged function word", 1.0
            e.glosses = [{"english": CLOSED_CLASS[word][1], "method": "hand-written"}]
        elif word in NAGA_PROPER_NOUNS:
            e.pos, e.pos_method, e.pos_confidence = "PROPN", "Naga place and tribe names", 1.0
        projected = votes.get(word)
        top_tag, top_votes, total = "", 0, 0
        if projected:
            (top_tag, top_votes), total = projected.most_common(1)[0], sum(projected.values())
            if top_tag in CLOSED_TAGS:
                top_tag = ""
        if word in verbs:
            root, suffix, meaning = verbs[word]
            e.root, e.morphology = root, f"{root}- + -{suffix} ({meaning})"
            e.features = [meaning]
            strong = suffix in STRONG_SUFFIXES
            if e.pos == "Unknown" and (strong or top_tag in ("VERB", "AUX", "")):
                e.pos, e.pos_method = "VERB", "verb paradigm (suffix analysis)"
                e.pos_confidence = 0.9 if strong else 0.7
        if e.pos == "Unknown" and top_tag and total >= 3 and top_votes / total >= 0.5:
            e.pos, e.pos_method = top_tag, f"projected from aligned English ({top_votes} of {total} alignments)"
            e.pos_confidence = round(top_votes / total, 2)
        if e.pos == "Unknown" and e.section_pos:
            e.pos, e.pos_method, e.pos_confidence = e.section_pos, "domain of a curated word list", 0.6
        if e.pos == "Unknown" and e.display:
            e.pos, e.pos_method, e.pos_confidence = "PROPN", "written with a capital mid-sentence", 0.8
        if not e.root:
            if word.endswith("khan") and len(word) > 6 and word[:-4] in entries:
                e.root, e.morphology, e.features = word[:-4], f"{word[:-4]} + -khan (plural)", ["plural"]
            else:
                for postposition in ATTACHED_POSTPOSITIONS:
                    base = word[: -len(postposition)]
                    if word.endswith(postposition) and len(base) >= 2 and base in entries and entries[base].nt_count >= 3 and word not in CLOSED_CLASS:
                        e.root, e.morphology = base, f"{base} + {postposition} (attached postposition)"
                        e.features = [f"attached {postposition}"]
                        break
        if not e.glosses and word in glosses:
            e.glosses = glosses[word][:2]
        if not e.origin:
            e.origin = "Nagamese" if e.nt_count or e.keyboard_weight else ""

    # Spelling variants: the most frequent spelling in each fold group is the headword.
    groups: dict[str, list[str]] = defaultdict(list)
    for word in entries:
        groups[fold(word)].append(word)
    for members in groups.values():
        if len(members) < 2:
            continue
        members.sort(key=lambda w: (-entries[w].nt_count, -entries[w].keyboard_weight, w))
        head = members[0]
        entries[head].variants = members[1:]
        for other in members[1:]:
            entries[other].canonical = head

    # Status: attested in real text, curated by people, or a candidate awaiting a speaker.
    kept, statuses = [], Counter()
    verified: dict[str, dict] = {}
    for word, e in entries.items():
        decision = decisions.get(word)
        if decision:
            verdict = decision["decision"]
            if verdict in ("reject", "no", "remove"):
                rejected.append((word, "; ".join(s["name"] for s in e.sources), f"rejected by {decision.get('reviewer') or 'a speaker'}"))
                continue
            if verdict.startswith("variant"):
                target = verdict.split(":", 1)[-1].strip() if ":" in verdict else verdict.split()[-1]
                if target and target != word:
                    e.canonical = target
            if decision.get("correct_pos"):
                e.pos, e.pos_method, e.pos_confidence = decision["correct_pos"], "verified by a speaker", 1.0
            verified[word] = decision
        if e.nt_count:
            status = "attested"
        elif e.noisy_only:
            in_scraped = any(s.get("kind") == "scraped" for s in e.sources)
            if word in HINDI_FUNCTION_WORDS:
                rejected.append((word, "; ".join(s["name"] for s in e.sources), "Hindi function word, not Nagamese"))
                continue
            if in_scraped and word in ENGLISH_BOILERPLATE:
                rejected.append((word, "; ".join(s["name"] for s in e.sources), "web page boilerplate"))
                continue
            status = "candidate"
        else:
            status = "curated"
        statuses[status] += 1
        kept.append((word, e, status))

    kept.sort(key=lambda item: (-item[1].nt_count, -item[1].keyboard_weight, item[0]))
    records = []
    for index, (word, e, status) in enumerate(kept, start=1):
        register = "both" if e.nt_count and (e.keyboard_weight or e.domains) else "scripture" if e.nt_count else "everyday"
        records.append({
            "id": f"LKB-{index:05d}",
            "lemma": word,
            "display": e.display or word,
            "root": e.root or word,
            "pos_category": e.pos,
            "pos": {"tag": e.pos, "method": e.pos_method, "confidence": e.pos_confidence},
            "morphology": e.morphology,
            "features": e.features,
            "english_definition": (verified.get(word) or {}).get("correct_gloss", ""),  # only a speaker-verified meaning
            "gloss_candidates": e.glosses,
            "frequency_count": e.nt_count,
            "keyboard_weight": e.keyboard_weight,
            "register": register,
            "etymology_origin": e.origin or "unknown",
            "domains": sorted(e.domains),
            "canonical": e.canonical or word,
            "orthographic_variants": e.variants,
            "sources": e.sources,
            "status": status,
            "is_validated": word in verified,
            "verified_by": (verified.get(word) or {}).get("reviewer") or None,
        })

    LEXICON_DIR.mkdir(parents=True, exist_ok=True)
    LEXICON_JSON.write_text(json.dumps(records, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    with LEXICON_TSV.open("w", encoding="utf-8", newline="") as handle:
        handle.write("id\tword\tdisplay\tstatus\tpos\tpos_method\troot\tmorphology\tgloss_candidates\tnt_count\tkeyboard_weight\tregister\torigin\tdomains\tcanonical\tvariants\tsources\n")
        for r in records:
            handle.write("\t".join([
                r["id"], r["lemma"], r["display"], r["status"], r["pos_category"], r["pos"]["method"], r["root"],
                r["morphology"], "; ".join(g["english"] for g in r["gloss_candidates"]), str(r["frequency_count"]),
                str(r["keyboard_weight"]), r["register"], r["etymology_origin"], ",".join(r["domains"]),
                r["canonical"], ",".join(r["orthographic_variants"]), "; ".join(s["name"] for s in r["sources"]),
            ]) + "\n")
    with REJECTED_TSV.open("w", encoding="utf-8", newline="") as handle:
        handle.write("word\tsource\treason\n")
        handle.writelines(f"{w}\t{s}\t{reason}\n" for w, s, reason in rejected)

    # Review queue for a speaker: function words, then the most frequent words, then candidates.
    open_records = [r for r in records if r["lemma"] not in decisions]
    queue = [r for r in open_records if r["pos"]["method"] == "hand-tagged function word"]
    queue += [r for r in open_records if r["status"] == "attested" and r not in queue][:300]
    queue += [r for r in open_records if r["status"] == "candidate"]
    with REVIEW_TSV.open("w", encoding="utf-8", newline="") as handle:
        handle.write("id\tword\tstatus\tpos\tgloss_candidates\tmorphology\tvariants\tdomains\tdecision\tcorrect_pos\tcorrect_gloss\tnote\n")
        for r in queue:
            handle.write("\t".join([
                r["id"], r["lemma"], r["status"], r["pos_category"],
                "; ".join(g["english"] for g in r["gloss_candidates"]), r["morphology"],
                ",".join(r["orthographic_variants"]), ",".join(r["domains"]), "", "", "", "",
            ]) + "\n")

    tagged = sum(1 for r in records if r["pos_category"] != "Unknown")
    token_total = sum(counts.values())
    tagged_tokens = sum(counts[r["lemma"]] for r in records if r["pos_category"] != "Unknown")
    stats = {
        "built_at": time.strftime("%Y-%m-%d %H:%M"),
        "entries": len(records),
        "by_status": dict(statuses),
        "rejected": len(rejected),
        "pos_tagged_entries": tagged,
        "pos_tagged_share_of_running_text": round(tagged_tokens / token_total, 4),
        "pos_methods": dict(Counter(r["pos"]["method"].split(" (")[0] for r in records if r["pos"]["method"])),
        "pos_tags": dict(Counter(r["pos_category"] for r in records)),
        "verb_forms_analysed": sum(1 for r in records if "suffix analysis" in r["pos"]["method"] or "-" in r["morphology"]),
        "variant_groups": sum(1 for r in records if r["orthographic_variants"]),
        "entries_with_gloss_candidates": sum(1 for r in records if r["gloss_candidates"]),
        "names_with_display_form": sum(1 for r in records if r["display"] != r["lemma"]),
        "registers": dict(Counter(r["register"] for r in records)),
        "domains": dict(Counter(d for r in records for d in r["domains"]).most_common()),
        "review_queue": len(queue),
        "verified_by_speakers": sum(1 for r in records if r["is_validated"]),
    }
    STATS_JSON.write_text(json.dumps(stats, indent=2) + "\n", encoding="utf-8")
    return stats


