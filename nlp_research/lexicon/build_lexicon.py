def fold(word: str) -> str:
    """The spelling-variant key: sh/s, ee/i, oo/u, v/b and doubled letters treated as one."""
    word = word.replace("sh", "s").replace("ee", "i").replace("oo", "u").replace("v", "b")
    return re.sub(r"(.)\1+", r"\1", word)


def read_vocab_sections(path: Path) -> list[tuple[str, str]]:
    """(word, section heading) for every word line in an earlier thematic list."""
    section, found = "", []
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if stripped.startswith("#"):
            heading = stripped.strip("#= ").strip()
            if heading and not set(heading) <= set("="):
                section = heading
            continue
        word = stripped.lower()
        if word:
            found.append((word, section))
    return found


def domain_for(section: str) -> str | None:
    lowered = section.lower()
    return next((domain for key, domain in DOMAIN_KEYWORDS if key in lowered), None)


def section_kind(section: str) -> str:
    lowered = section.lower()
    if "scrap" in lowered or "automated" in lowered:
        return "scraped"
    if "hindi" in lowered:
        return "hindi"
    if "variant" in lowered:
        return "variants"
    if "english" in lowered or "loanword" in lowered or "borrowed" in lowered or "code-switching" in lowered:
        return "english"
    return "nagamese"


def nt_counts_and_display() -> tuple[Counter, dict[str, str]]:
    """Word counts from the New Testament, and the capitalised form of words written as names."""
    tokenizer = NagameseTokenizer()
    counts: Counter = Counter()
    capitalised: Counter = Counter()
    seen_mid: Counter = Counter()
    for sentence in sentences():
        counts.update(tokenizer.tokenize(sentence))
        # A word right after the start, a full stop, colon or opening quote is capitalised
        # by position; only capitals elsewhere say a word is a name.
        for match in re.finditer(r"(?:(^)|([.?!:;“\"‘'(]\s*)|\s)([A-Za-z]{2,})", sentence):
            token = match.group(3)
            if match.group(1) is not None or match.group(2):
                continue
            seen_mid[token.lower()] += 1
            if token[0].isupper():
                capitalised[token] += 1
    # Common words keep lowercase even when the Bible capitalises them (Isor, Probhu):
    # a display form is only for names, never for a word on the keyboard's everyday list.
    everyday = set(builtin_words())
    display = {}
    for token, count in capitalised.items():
        word = token.lower()
        if count >= 3 and count / seen_mid[word] >= 0.9 and word not in CLOSED_CLASS and word not in everyday:
            display[word] = token
    return counts, display


def project_pos(pairs: list[tuple[str, str]], iterations: int = 5) -> dict[str, Counter]:
    """Tag the English side, align words with IBM Model 1 both ways, and let each Nagamese word vote."""
    import nltk

    from nlp_research.translation.glossary import _ibm_model1

    tokenizer = NagameseTokenizer()
    tokenised = []
    for english, nagamese in pairs:
        en_tokens = re.findall(r"[A-Za-z]+(?:'[a-z]+)?", english)
        nag_tokens = tokenizer.tokenize(nagamese)
        if en_tokens and nag_tokens and len(en_tokens) <= 80 and len(nag_tokens) <= 80:
            tokenised.append((en_tokens, nag_tokens))
    lowered = [([w.lower() for w in en], nag) for en, nag in tokenised]
    nag_given_en = _ibm_model1(lowered, iterations)  # t[nag][en]
    en_given_nag = _ibm_model1([(nag, en) for en, nag in lowered], iterations)  # t[en][nag]
    votes: dict[str, Counter] = defaultdict(Counter)
    for (en_tokens, nag_tokens), (en_lower, _) in zip(tokenised, lowered):
        tags = [tag for _, tag in nltk.pos_tag(en_tokens)]
        for nag in set(nag_tokens):
            row = nag_given_en.get(nag, {})
            best, best_score = -1, 0.0
            for index, english in enumerate(en_lower):
                score = row.get(english, 0.0) * en_given_nag.get(english, {}).get(nag, 0.0)
                if score > best_score:
                    best, best_score = index, score
            if best >= 0 and best_score > 1e-4:
                upos = PTB_TO_UPOS.get(tags[best])
                if upos is None and tags[best].startswith("VB"):
                    upos = "VERB"
                if upos:
                    votes[nag][upos] += 1
    return votes


def analyse_verbs(words: set[str]) -> dict[str, tuple[str, str, str]]:
    """word -> (root, suffix, meaning) for forms of verbs whose root takes at least three endings."""
    endings = sorted({**STRONG_SUFFIXES, **WEAK_SUFFIXES}.items(), key=lambda item: -len(item[0]))
    split: dict[str, tuple[str, str]] = {}
    for word in words:
        bare = word[2:] if word.startswith("na") and word[2:] in words else word
        for suffix, _ in endings:
            if bare.endswith(suffix) and len(bare) - len(suffix) >= 2:
                split[word] = (bare[: -len(suffix)], suffix)
                break
    paradigm: dict[str, set[str]] = defaultdict(set)
    for root, suffix in split.values():
        paradigm[root].add(suffix)
    analyses = {}
    for word, (root, suffix) in split.items():
        if len(paradigm[root]) >= 3:
            meaning = {**STRONG_SUFFIXES, **WEAK_SUFFIXES}[suffix]
            if word.startswith("na") and not word.startswith(root):
                meaning = "negative, " + meaning
            analyses[word] = (root, suffix, meaning)
    return analyses


def load_glosses() -> dict[str, list[dict]]:
    found: dict[str, list[dict]] = defaultdict(list)
    if GLOSSARY_TSV.is_file():
        with GLOSSARY_TSV.open(encoding="utf-8", newline="") as handle:
            for row in csv.DictReader(handle, delimiter="\t"):
                found[row["nagamese"]].append({"english": row["english"], "score": float(row["score"]), "method": "ibm1-aligned-verses"})
    return found


def _score_research_row(row: dict) -> float:
    """Score a researched word for how likely it is to be used in everyday Nagamese.

    Higher = more likely to keep. Used to rank English/Hindi words and keep only top N.
    """
    score = float(row.get("confidence", 0.5))
    # Boost everyday register words
    if row.get("register") == "everyday":
        score += 0.3
    # Boost words with web verification
    if row.get("method") == "web-verified":
        score += 0.2
    # Boost words in high-frequency domains
    high_freq_domains = {"food", "education", "health", "travel", "money", "home", "slang", "technology", "work"}
    if set(row.get("domains", [])) & high_freq_domains:
        score += 0.15
    # Penalise very long words (obscure dictionary terms)
    if len(row.get("word", "")) > 12:
        score -= 0.3
    return score


def read_research(research_dir: Path = RESEARCH_DIR) -> tuple[list[tuple[str, dict]], list[tuple[str, dict]], int]:
    """(shard name, row) for new words and for annotations of listed words, and the number of invalid rows skipped.

    Rows that fail validate_research.check_row are skipped, so a half-finished shard
    never puts an empty field into the lexicon.

    NEW words from English and Hindi origins are scored and capped at MAX_ENGLISH_BASE
    and MAX_HINDI_BASE respectively, keeping only the most everyday/useful words.
    """
    all_new_rows: list[tuple[str, dict]] = []
    enrich_rows: list[tuple[str, dict]] = []
    skipped = 0
    for path in sorted(research_dir.glob("*.jsonl")):
        target = all_new_rows if path.name.startswith("new_") else enrich_rows
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                skipped += 1
                continue
            if check_row(row):
                skipped += 1
                continue
            target.append((path.stem, row))

    # Cap new English and Hindi words by keeping only the top-scoring ones.
    english_new = [(s, r) for s, r in all_new_rows if r.get("origin", "") in _ENGLISH_ORIGINS]
    hindi_new = [(s, r) for s, r in all_new_rows if r.get("origin", "") in _HINDI_ORIGINS]
    other_new = [(s, r) for s, r in all_new_rows if r.get("origin", "") not in _ENGLISH_ORIGINS | _HINDI_ORIGINS]

    english_new.sort(key=lambda x: _score_research_row(x[1]), reverse=True)
    hindi_new.sort(key=lambda x: _score_research_row(x[1]), reverse=True)

    capped_english = english_new[:MAX_ENGLISH_BASE]
    capped_hindi = hindi_new[:MAX_HINDI_BASE]
    skipped += len(english_new) - len(capped_english) + len(hindi_new) - len(capped_hindi)

    new_rows = other_new + capped_english + capped_hindi
    return new_rows, enrich_rows, skipped


